/** 一级分类名 → categoryId */
const catNameToId = (name: string): string => {
  let h = 0
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0
  return `cat-${h.toString(36)}`
}

/** 二级岗位名 → subId */
export const subNameToId = (name: string): string => {
  let h = 0
  for (let i = 0; i < name.length; i++) h = (h * 33 + name.charCodeAt(i)) >>> 0
  return `sub-${h.toString(36)}`
}

/** 一级分类 id → 名称 反查表 */
export const CATEGORY_ID_TO_NAME: Record<string, string> = {}
/** 一级分类名 → id */
export const CATEGORY_NAME_TO_ID: Record<string, string> = {}
/** 二级岗位 id → 名称 反查表 */
export const SUB_ID_TO_NAME: Record<string, string> = {}

const _categoryTree: CategoryNode[] = []

Object.entries(CATEGORY_TREE_RAW).forEach(([cat, subs], idx) => {
  const catId = catNameToId(cat)
  CATEGORY_ID_TO_NAME[catId] = cat
  CATEGORY_NAME_TO_ID[cat] = catId
  const node: CategoryNode = {
    id: catId,
    name: cat,
    sort: idx,
    children: subs.map((s, j) => {
      const subId = subNameToId(s)
      SUB_ID_TO_NAME[subId] = s
      return { id: subId, name: s, sort: j, children: [] }
    }),
  }
  _categoryTree.push(node)
})

export const categoryTree: CategoryNode[] = _categoryTree

